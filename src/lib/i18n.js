function normLang(input) {
  if (!input) return null;
  const s = String(input).toLowerCase();
  if (s.startsWith('zh')) return 'zh';
  if (s.startsWith('en')) return 'en';
  return null;
}

/** Resolve the UI language: ?lang= wins, then the cookie, then English. */
function pickLang(req) {
  const fromQuery = normLang(req.query && req.query.lang);
  if (fromQuery) return fromQuery;
  const cookie = parseCookie(req.headers.cookie || '', 'l10n_lang');
  return normLang(cookie) || DEFAULT;
}

function parseCookie(header, name) {
  for (const part of header.split(';')) {
    const i = part.indexOf('=');
    if (i > 0 && part.slice(0, i).trim() === name) return decodeURIComponent(part.slice(i + 1).trim());
  }
  return null;
}

/** Returns a t() bound to a language, with {var} interpolation. */
function translator(lang) {
  const table = DICT[lang] || DICT[DEFAULT];
  const fallback = DICT[DEFAULT];
  return function t(key, vars) {
    let s = table[key] != null ? table[key] : fallback[key] != null ? fallback[key] : key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Plain dictionary for client scripts (window.T). */
function clientDict(lang) {
  return DICT[lang] || DICT[DEFAULT];
}

